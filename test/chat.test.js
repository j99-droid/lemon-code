// Run with `npm test`. Checks which transcript lines the chat view shows.
const test = require('node:test');
const assert = require('node:assert');
const { chatMessage } = require('../src/chat');

const line = (o) => JSON.stringify({ uuid: 'u1', ...o });

test('your prompt shows as a user bubble', () => {
  const m = chatMessage(line({ type: 'user', message: { role: 'user', content: 'make it blue' } }));
  assert.deepStrictEqual(m, { id: 'u1', role: 'user', text: 'make it blue' });
});

test("Claude's text shows, tool calls and thinking don't", () => {
  const text = chatMessage(line({ type: 'assistant', message: { content: [{ type: 'text', text: 'Done.' }] } }));
  assert.strictEqual(text.text, 'Done.');
  assert.strictEqual(chatMessage(line({ type: 'assistant', message: { content: [{ type: 'tool_use', name: 'Bash', input: {} }] } })), null);
  assert.strictEqual(chatMessage(line({ type: 'assistant', message: { content: [{ type: 'thinking', thinking: 'hmm' }] } })), null);
});

test('tool results, helper work, meta and command echoes are hidden', () => {
  const hidden = [
    { type: 'user', message: { content: [{ type: 'tool_result', content: 'output' }] } },
    { type: 'user', isSidechain: true, message: { content: 'helper prompt' } },
    { type: 'user', isMeta: true, message: { content: 'meta' } },
    { type: 'user', message: { content: '<command-name>/clear</command-name>' } },
    { type: 'user', message: { content: '<local-command-stdout>ok</local-command-stdout>' } },
    { type: 'user', message: { content: 'Caveat: the messages below were generated by the user' } },
    { type: 'api-request-blob', message: { content: [{ type: 'text', text: 'system prompt' }] } },
  ];
  for (const o of hidden) assert.strictEqual(chatMessage(line(o)), null, JSON.stringify(o));
});

test("Claude's questions show as a bubble marked ask", () => {
  const m = chatMessage(line({ type: 'assistant', message: { content: [{ type: 'tool_use', name: 'AskUserQuestion',
    input: { questions: [{ question: 'Which colour?' }, { question: 'How big?' }] } }] } }));
  assert.deepStrictEqual(m, { id: 'u1', role: 'assistant', text: 'Which colour?\n\nHow big?', ask: true });
});

test('an interrupt is a note, and bad lines are ignored', () => {
  const m = chatMessage(line({ type: 'user', message: { content: [{ type: 'text', text: '[Request interrupted by user]' }] } }));
  assert.strictEqual(m.role, 'note');
  assert.strictEqual(chatMessage('{not json'), null);
  assert.strictEqual(chatMessage(''), null);
});

test('a line split mid-character across two reads comes out whole', () => {
  const fs = require('fs');
  const os = require('os');
  const path = require('path');
  const { ChatFeed } = require('../src/chat');
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'lemon-chat-')), 's.jsonl');
  const bytes = Buffer.from(`${line({ type: 'user', message: { content: 'lemon 🍋 time' } })}\n`);
  const cut = bytes.indexOf(Buffer.from('🍋')) + 2; // inside the emoji's four bytes
  const feed = new ChatFeed('s');
  feed.file = file;
  const seen = [];
  feed.on('messages', (m) => seen.push(...m));
  fs.writeFileSync(file, bytes.subarray(0, cut));
  feed.read();
  fs.appendFileSync(file, bytes.subarray(cut));
  feed.read();
  assert.deepStrictEqual(seen.map((m) => m.text), ['lemon 🍋 time']);
});
